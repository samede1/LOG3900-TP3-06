def add(a,b):

    """ Rôle: Fonction d'addition de 2 opérandes. 
        Entrées: { a: int ou double, b: int ou double }. 
        Sorties: { int ou double }. """

    return a + b

def subtract(a,b):

    """ Rôle: Fonction de soustraction de 2 opérandes. 
        Entrées: { a: int ou double, b: int ou double }. 
        Sorties: { int ou double }. """
    
    return a - b

def multiply(a,b):

    """ Rôle: Fonction de multiplication de 2 opérandes. 
        Entrées: {  a: int ou double, b: int ou double }. 
        Sorties: { int ou double }. """
    
    return a * b

def divide(a,b):

    """ Rôle: Fonction de division de 2 opérandes. 
        Entrées: { a: int ou double, b: int ou double }. 
        Sorties: { int ou double }. """
    
    return a // b
